class PerfectMarketSimulator:
    """
    Simulates an underlying asset (like an index) and a corresponding options chain.
    """
    def __init__(self, config: PerfectTradingConfig):
        self.config = config
        self.support = 17500
        self.resistance = 18500
        self.underlying_prices = self._generate_trending_prices()
        self.trend_direction = random.choice([-1, 1]) * 0.00005
        self.volatility = 0.001 * config.VOLATILITY_MULTIPLIER
        self.last_price = self.underlying_prices[-1]
        self.cycle = 0

    def _generate_trending_prices(self) -> List[float]:
        """Generate trending initial prices for the underlying asset."""
        print(f"📊 Generating {self.config.INITIAL_PRICES} trending prices for {self.config.SYMBOL}...")
        prices = []
        current = 18000.0  # A realistic starting point for an index
        trend = random.uniform(-0.0001, 0.0001)

        for _ in range(self.config.INITIAL_PRICES):
            change = trend + np.random.normal(0, 0.0005)
            current *= (1 + change)
            current = max(self.support, min(self.resistance, current))
            prices.append(round(current, 2))

        trend_direction = "UP" if prices[-1] > prices[0] else "DOWN"
        print(f"✅ Initial trend: {trend_direction} ({prices[0]:.2f} → {prices[-1]:.2f})")
        return prices

    def generate_price_and_options(self) -> Tuple[float, List[Dict]]:
        """Generate a new price for the underlying and a corresponding options chain."""
        self.cycle += 1
        distance_to_mid = (18000 - self.last_price) / 18000
        mean_reversion = distance_to_mid * 0.0001
        trend = self.trend_direction
        volatility = self.volatility * (1 + abs(distance_to_mid))
        change = trend + mean_reversion + np.random.normal(0, volatility)
        new_price = self.last_price * (1 + change)

        if new_price < self.support:
            new_price = self.support + random.uniform(0, 20)
        elif new_price > self.resistance:
            new_price = self.resistance - random.uniform(0, 20)

        new_price = round(new_price, 2)
        self.last_price = new_price
        self.underlying_prices.append(new_price)

        if len(self.underlying_prices) > 2000:
            self.underlying_prices = self.underlying_prices[-2000:]

        options_chain = self._generate_options_chain(new_price)
        return new_price, options_chain

    def _generate_options_chain(self, underlying_price: float) -> List[Dict]:
        """Generate a simplified options chain around the current underlying price."""
        step = self.config.OPTIONS_STRIKE_STEP
        atm_strike = round(underlying_price / step) * step
        chain = []
        for i in range(-3, 4):
            strike = atm_strike + (i * step)
            # Calculate simple intrinsic value based prices
            call_premium = max(0.05, round(underlying_price - strike, 2)) + random.uniform(1, 5)
            put_premium = max(0.05, round(strike - underlying_price, 2)) + random.uniform(1, 5)

            chain.append({'symbol': f"NIFTY_CE_{strike}", 'type': 'CE', 'strike': strike, 'price': round(call_premium, 2)})
            chain.append({'symbol': f"NIFTY_PE_{strike}", 'type': 'PE', 'strike': strike, 'price': round(put_premium, 2)})
        return chain

    def get_price_history(self, count: int = 100) -> List[float]:
        """Get recent price history of the underlying asset."""
        return self.underlying_prices[-count:]


