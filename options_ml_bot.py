# FEATURE ENGINEERING
# ============================================================================

def create_features(prices: List[float], config: PerfectTradingConfig) -> pd.DataFrame:
    """Create features from price data for the ML model."""
    if len(prices) < config.EMA_LONG:
        return pd.DataFrame()

    df = pd.DataFrame({'price': prices})

    # --- Standard Indicators ---
    # RSI
    delta = df['price'].diff()
    gain = (delta.where(delta > 0, 0)).rolling(window=config.RSI_PERIOD).mean()
    loss = (-delta.where(delta < 0, 0)).rolling(window=config.RSI_PERIOD).mean()
    rs = gain / loss
    df['rsi'] = 100 - (100 / (1 + rs))
    df['rsi'] = df['rsi'].replace([np.inf, -np.inf], np.nan).fillna(50) # Handle inf and fill NaN

    # EMAs
    df['ema_short'] = df['price'].ewm(span=config.EMA_SHORT, adjust=False).mean()
    df['ema_long'] = df['price'].ewm(span=config.EMA_LONG, adjust=False).mean()
    df['ema_diff'] = (df['ema_short'] - df['ema_long']) / df['price']

    # MACD
    ema_fast = df['price'].ewm(span=config.MACD_FAST, adjust=False).mean()
    ema_slow = df['price'].ewm(span=config.MACD_SLOW, adjust=False).mean()
    df['macd'] = ema_fast - ema_slow
    df['macd_signal'] = df['macd'].ewm(span=config.MACD_SIGNAL, adjust=False).mean()
    df['macd_hist'] = df['macd'] - df['macd_signal']

    # --- Price-based Features ---
    # Price change (Momentum)
    df['momentum_1'] = df['price'].pct_change(periods=1)
    df['momentum_5'] = df['price'].pct_change(periods=5)
    df['momentum_10'] = df['price'].pct_change(periods=10)

    # Volatility (standard deviation of returns)
    df['volatility_5'] = df['momentum_1'].rolling(window=5).std()
    df['volatility_10'] = df['momentum_1'].rolling(window=10).std()

    # Distance from moving averages
    df['dist_ema_short'] = (df['price'] - df['ema_short']) / df['price']
    df['dist_ema_long'] = (df['price'] - df['ema_long']) / df['price']

    # --- Target Variable ---
    # The target is the future price direction.
    # 1 for buy (price will increase), -1 for sell (price will decrease), 0 for hold.
    future_price = df['price'].shift(-MLConfig.LOOKAHEAD_PERIOD)
    price_change = (future_price - df['price']) / df['price']

    df['target'] = 0
    df.loc[price_change > 0.005, 'target'] = 1  # Buy if price increases by 0.5%
    df.loc[price_change < -0.005, 'target'] = -1 # Sell if price decreases by 0.5%

    # Fill initial NaN values and return
    return df.dropna().reset_index(drop=True)


