class PerfectTradingBot:
    """An options trading bot powered by an ML model."""

    def __init__(self, config: PerfectTradingConfig, ml_config: MLConfig):
        self.config = config
        self.ml_config = ml_config

        # Initialize components
        print("\n" + "=" * 60)
        print("🤖 INITIALIZING OPTIONS ML TRADING BOT")
        print("=" * 60)

        # Train or load the model
        self.model = train_model(config, ml_config)

        self.market = PerfectMarketSimulator(config)
        self.strategy = OptionsMLStrategy(config, self.model)

        # Trading state
        self.balance = config.INITIAL_BALANCE
        self.positions = []  # List of dicts with additional info
        self.trade_history = []

        # Statistics
        self.cycle = 0
        self.start_time = dt.now()
        self.total_pnl = 0.0
        self.total_trades = 0
        self.winning_trades = 0
        self.total_buys = 0
        self.total_sells = 0

        # Risk management
        self.max_drawdown = 0.0
        self.peak_portfolio = config.INITIAL_BALANCE

        # Display
        print("\n" + "=" * 60)
        print("🎯 PERFECT TRADING BOT - BALANCED STRATEGY")
        print("=" * 60)
        print(f"📊 Symbol: {config.SYMBOL}")
        print(f"💰 Initial Balance: ₹{config.INITIAL_BALANCE:,.2f}")
        print(f"⚡ Update Interval: {config.UPDATE_INTERVAL} seconds")
        print(f"🎯 Strategy: Balanced RSI/EMA with Profit Taking")
        print(f"📈 Position Size: {config.POSITION_SIZE} shares")
        print(f"🛡️  Stop Loss: {config.STOP_LOSS_PCT}% | Take Profit: {config.TAKE_PROFIT_PCT}%")
        print(f"💰 Partial Profit Taking: {'ENABLED' if config.PARTIAL_PROFIT_TAKING else 'DISABLED'}")
        print("=" * 60)

    def execute_buy(self, option: Dict, confidence: float, reasons: List[str]) -> bool:
        """Execute an options buy order."""
        if len(self.positions) >= self.config.MAX_POSITIONS:
            print("  ⚠️  Max positions reached - cannot buy")
            return False

        position_size = self.config.POSITION_SIZE
        cost = position_size * option['price']

        if self.balance >= cost:
            self.balance -= cost
            self.positions.append({
                'symbol': option['symbol'],
                'type': option['type'],
                'quantity': position_size,
                'entry_price': option['price'],
                'entry_time': dt.now(),
                'stop_loss': option['price'] * (1 - self.config.STOP_LOSS_PCT / 100),
                'take_profit': option['price'] * (1 + self.config.TAKE_PROFIT_PCT / 100),
                'highest_price': option['price'],
                'reasons': reasons
            })

            self.total_trades += 1
            self.total_buys += 1
            print(f"\n  🟢 BUY #{self.total_trades} ({option['symbol']})")
            print(f"     Quantity: {position_size} contracts")
            print(f"     Price: ₹{option['price']:.2f}")
            print(f"     Cost: ₹{cost:,.2f}")
            print(f"     Confidence: {confidence:.1%}")
            return True
        else:
            print(f"  ⚠️  Insufficient funds to buy {option['symbol']}")
            return False

    def check_and_execute_sells(self, options_chain: List[Dict]) -> List[float]:
        """Check for stop loss, take profit, and trailing stop triggers for options."""
        pnls = []
        positions_to_remove = []

        for i, pos in enumerate(self.positions):
            current_option = next((o for o in options_chain if o['symbol'] == pos['symbol']), None)
            if not current_option:
                continue # Option may have expired or is not in the current chain

            current_price = current_option['price']
            pos['highest_price'] = max(pos['highest_price'], current_price)

            if current_price <= pos['stop_loss']:
                pnl = self._execute_sell(i, current_price, "STOP_LOSS")
                pnls.append(pnl)
                positions_to_remove.append(i)
            elif current_price >= pos['take_profit']:
                pnl = self._execute_sell(i, current_price, "TAKE_PROFIT")
                pnls.append(pnl)
                positions_to_remove.append(i)
            elif self.config.TRAILING_STOP_PCT > 0:
                trail_stop = pos['highest_price'] * (1 - self.config.TRAILING_STOP_PCT / 100)
                if current_price <= trail_stop:
                    pnl = self._execute_sell(i, current_price, "TRAILING_STOP")
                    pnls.append(pnl)
                    positions_to_remove.append(i)

        # This part of the original code is now handled in run_cycle
        # for i in sorted(positions_to_remove, reverse=True):
        #     self.positions.pop(i)
        return positions_to_remove, pnls

    def _execute_sell(self, idx: int, price: float, reason: str) -> float:
        """Execute sell of an entire options position."""
        pos = self.positions[idx]
        revenue = pos['quantity'] * price
        pnl = revenue - (pos['quantity'] * pos['entry_price'])
        self.balance += revenue
        self.total_pnl += pnl
        self.total_trades += 1
        self.total_sells += 1
        if pnl > 0: self.winning_trades += 1

        print(f"\n  🔴 SELL #{self.total_trades} ({pos['symbol']})")
        print(f"     Price: ₹{price:.2f} | Entry: ₹{pos['entry_price']:.2f}")
        pnl_color = "\033[92m" if pnl > 0 else "\033[91m"
        print(f"     P&L: {pnl_color}₹{pnl:+,.2f}{self.config.RESET_COLOR}")
        print(f"     Reason: {reason}")
        return pnl

    def run_cycle(self) -> Dict:
        """Run one options trading cycle."""
        self.cycle += 1
        underlying_price, options_chain = self.market.generate_price_and_options()
        price_history = self.market.get_price_history(200)

        # Automatic sells (SL/TP)
        auto_sell_indices, auto_sell_pnls = self.check_and_execute_sells(options_chain)

        # ML Signal Generation
        option_to_buy, idx_to_sell, confidence, reasons = self.strategy.generate_signal(price_history, options_chain, self.positions)

        signal_executed = False
        signal_pnl = 0.0

        if option_to_buy:
            signal_executed = self.execute_buy(option_to_buy, confidence, reasons)
        elif idx_to_sell is not None:
            option_price = next((o['price'] for o in options_chain if o['symbol'] == self.positions[idx_to_sell]['symbol']), self.positions[idx_to_sell]['entry_price'])
            signal_pnl = self._execute_sell(idx_to_sell, option_price, " ".join(reasons))
            auto_sell_indices.append(idx_to_sell)
            signal_executed = True

        # Clean up sold positions
        for i in sorted(list(set(auto_sell_indices)), reverse=True):
            if i < len(self.positions):
                self.positions.pop(i)

        portfolio_value = self._calculate_portfolio_value(options_chain)
        self._update_drawdown(portfolio_value)

        return {
            'cycle': self.cycle,
            'timestamp': dt.now(),
            'price': underlying_price,
            'portfolio_value': portfolio_value,
            'positions': len(self.positions),
            'total_pnl': self.total_pnl,
            'reasons': reasons,
            'options_chain': options_chain
        }

    def _calculate_portfolio_value(self, options_chain: List[Dict]) -> float:
        """Calculate total portfolio value based on current option prices."""
        position_value = 0
        for pos in self.positions:
            current_option = next((o for o in options_chain if o['symbol'] == pos['symbol']), None)
            if current_option:
                position_value += pos['quantity'] * current_option['price']
            else: # If option expires or disappears, value is entry price (conservative)
                position_value += pos['quantity'] * pos['entry_price']
        return self.balance + position_value

    def _calculate_drawdown(self, portfolio_value: float) -> float:
        """Calculate current drawdown."""
        if portfolio_value > self.peak_portfolio:
            self.peak_portfolio = portfolio_value
            return 0.0
        else:
            return (self.peak_portfolio - portfolio_value) / self.peak_portfolio * 100

    def _update_drawdown(self, portfolio_value: float):
        """Update maximum drawdown."""
        current_dd = self._calculate_drawdown(portfolio_value)
        if current_dd > self.max_drawdown:
            self.max_drawdown = current_dd

    def display_status(self, data: Dict):
        """Display status information for the options bot."""
        print(f"\n[Cycle {data['cycle']:03d}] {data['timestamp'].strftime('%H:%M:%S')}")
        print("-" * 60)
        price_str = f"💰 Underlying ({self.config.SYMBOL}): ₹{data['price']:.2f}"
        print(price_str)
        print(f"📈 Portfolio: ₹{data['portfolio_value']:,.2f}")
        pnl_color = "\033[92m" if data['total_pnl'] >= 0 else "\033[91m"
        print(f"🎯 Total P&L: {pnl_color}₹{data['total_pnl']:+,.2f}{self.config.RESET_COLOR}")

        if data['reasons']:
            print(f"   Signal: {data['reasons'][0]}")

        if self.positions:
            print(f"\n📦 Open Positions ({len(self.positions)}):")
            for pos in self.positions:
                current_option = next((o for o in data['options_chain'] if o['symbol'] == pos['symbol']), None)
                current_price = current_option['price'] if current_option else pos['entry_price']
                unrealized_pnl = (current_price - pos['entry_price']) * pos['quantity']
                pnl_color = "\033[92m" if unrealized_pnl >= 0 else "\033[91m"
                print(f"  - {pos['symbol']}: {pos['quantity']} @ ₹{pos['entry_price']:.2f} | Current: ₹{current_price:.2f}")
                print(f"    Unrealized P&L: {pnl_color}₹{unrealized_pnl:+,.2f}{self.config.RESET_COLOR}")

    def run(self, duration_hours: float = 0.5):
        """Run the perfect trading bot."""
        print(f"\n{'=' * 60}")
        print(f"🚀 PERFECT TRADING SESSION")
        print(f"{'=' * 60}")

        end_time = self.start_time + timedelta(hours=min(duration_hours, 2))  # Max 2 hours

        print(f"⏰ Session end time: {end_time.strftime('%H:%M:%S')}")
        print(f"   ({min(duration_hours, 2)} hours)")
        print(f"\n🎯 Starting balanced trading...")

        try:
            while dt.now() < end_time:
                # Run cycle
                cycle_data = self.run_cycle()

                # Display
                self.display_status(cycle_data)

                # Time info
                elapsed = (dt.now() - self.start_time).seconds / 3600
                remaining = (end_time - dt.now()).seconds / 3600

                print(f"\n{'=' * 50}")
                print(f"⏱️  Elapsed: {elapsed:.2f}h | Remaining: {remaining:.2f}h")
                print(f"⏳ Next update in {self.config.UPDATE_INTERVAL} seconds...")

                time.sleep(self.config.UPDATE_INTERVAL)

        except KeyboardInterrupt:
            print("\n\n🛑 Trading stopped by user")

        self.show_summary()

    def show_summary(self):
        """Show a summary of the options trading session."""
        print(f"\n{'=' * 60}")
        print(f"📊 OPTIONS TRADING SUMMARY")
        print(f"{'=' * 60}")

        _, options_chain = self.market.generate_price_and_options()
        portfolio_value = self._calculate_portfolio_value(options_chain)
        total_return = ((portfolio_value - self.config.INITIAL_BALANCE) / self.config.INITIAL_BALANCE) * 100

        print(f"\n📈 PERFORMANCE:")
        print(f"  - Final Portfolio: ₹{portfolio_value:,.2f}")
        print(f"  - Total Return: {total_return:+.2f}%")
        print(f"  - Total P&L: ₹{self.total_pnl:+,.2f}")
        print(f"  - Max Drawdown: {self.max_drawdown:.2f}%")
        print(f"\n{'=' * 60}")
        print("SESSION COMPLETE")
        print(f"{'=' * 60}")


