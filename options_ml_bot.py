class OptionsMLStrategy:
    """
    An options trading strategy that uses an ML model to predict the direction
    of the underlying asset and then buys calls or puts accordingly.
    """
    def __init__(self, config: PerfectTradingConfig, model: RandomForestClassifier):
        self.config = config
        self.model = model
        self.feature_names = model.feature_names_in_

    def generate_signal(self, underlying_prices: List[float], options_chain: List[Dict], current_positions: List[Dict]) -> Tuple[Optional[Dict], Optional[int], float, List[str]]:
        """
        Generate a signal to buy a call/put or sell an existing position.
        Returns: (option_to_buy, position_index_to_sell, confidence, reasons)
        """
        if len(underlying_prices) < self.config.EMA_LONG + 10:
            return None, None, 0.0, ["Not enough data for prediction"]

        # 1. Predict the direction of the underlying asset
        features_df = create_features(underlying_prices, self.config)
        if features_df.empty:
            return None, None, ["Feature creation failed"]

        latest_features = features_df.tail(1).drop(columns=['price', 'target'], errors='ignore')
        latest_features = latest_features[self.feature_names]

        prediction = self.model.predict(latest_features)[0]
        confidence = max(self.model.predict_proba(latest_features)[0])
        signal = int(prediction)

        # 2. Decide whether to sell an existing position
        if current_positions:
            # Simple strategy: if the model predicts a reversal, sell the position.
            position = current_positions[0] # Assuming one position at a time
            if (signal == -1 and position['type'] == 'CE') or \
               (signal == 1 and position['type'] == 'PE'):
                reason = f"ML predicts reversal. Selling {position['symbol']}."
                return None, 0, confidence, [reason]

        # 3. Decide whether to buy a new option
        if not current_positions and confidence > self.config.MIN_CONFIDENCE:
            underlying_price = underlying_prices[-1]
            atm_strike = round(underlying_price / self.config.OPTIONS_STRIKE_STEP) * self.config.OPTIONS_STRIKE_STEP

            option_to_buy = None
            if signal == 1: # Buy Call
                option_to_buy = next((o for o in options_chain if o['type'] == 'CE' and o['strike'] == atm_strike), None)
            elif signal == -1: # Buy Put
                option_to_buy = next((o for o in options_chain if o['type'] == 'PE' and o['strike'] == atm_strike), None)

            if option_to_buy:
                reason = f"ML predicts UP, buying Call." if signal == 1 else f"ML predicts DOWN, buying Put."
                return option_to_buy, None, confidence, [reason + f" (Conf: {confidence:.1%})"]

        return None, None, confidence, ["HOLD: No clear signal or position held"]


